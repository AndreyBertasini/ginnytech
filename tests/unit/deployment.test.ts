import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import astro from '../../astro.config.mjs';

test('Cloudflare Pages publishes the directory actually generated by Astro', () => {
  const root = fileURLToPath(new URL('../../', import.meta.url));
  const config = JSON.parse(readFileSync(new URL('../../wrangler.jsonc', import.meta.url), 'utf8'));
  assert.ok(config.pages_build_output_dir, 'Pages must declare its deployment directory instead of relying on an unknown dashboard default');
  assert.equal(resolve(root, config.pages_build_output_dir), resolve(root, String(astro.outDir)));
  assert.equal(astro.output, 'static');
  assert.ok(!config.assets, 'A Pages project must not also declare Workers asset configuration');
});
